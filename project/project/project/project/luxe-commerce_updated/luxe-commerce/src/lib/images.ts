function hashKey(key: string): number {
  let h = 0;
  for (let i = 0; i < key.length; i++) h = (h * 31 + key.charCodeAt(i)) >>> 0;
  return h;
}

export const productImage = (key: string): string => VAPE_IMAGES[hashKey(key) % VAPE_IMAGES.length];
export const heroImage = (n = 0): string => HERO_IMAGES[n % HERO_IMAGES.length];
export const blogImage = (key: string): string => BLOG_IMAGES[hashKey(key) % BLOG_IMAGES.length];
export const categoryImage = (key: string): string => CATEGORY_IMAGES[hashKey(key) % CATEGORY_IMAGES.length];
export const aboutImage = (n = 0): string => ABOUT_IMAGES[n % ABOUT_IMAGES.length];
export const promoImage = (n = 0): string => PROMO_IMAGES[n % PROMO_IMAGES.length];

// Resolve a user-provided image URL, falling back to a generated one if empty.
export const resolveImage = (url: string | null | undefined, fallback: string): string => {
  if (url && url.trim()) return url;
  return fallback;
};
